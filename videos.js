// WATCH HISTORY
// =================================


function saveWatchHistory(id){



let history =

JSON.parse(

localStorage.getItem(

"watchHistory"

)

)

|| [];





history = history.filter(

item=>item!==id

);





history.unshift(id);





history = history.slice(0,20);





localStorage.setItem(

"watchHistory",

JSON.stringify(history)

);



}
